#!/usr/bin/env node
// Generates src/schema.ts, the TypeScript types of ultrafast documents, from
// the document JSON Schema. No dependencies.
//
//   node scripts/gen-types.mjs [schema.json] [out.ts]
//
// The schema defaults to schema/v1.json, a copy of
// https://ultrafast.mov/schema/v1.json (`ultrafast schema`). Refresh the copy,
// run `npm run gen`, and commit both.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = process.argv[2] ?? join(root, "schema", "v1.json");
const outPath = process.argv[3] ?? join(root, "src", "schema.ts");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const defs = schema.$defs ?? {};

const pascal = (s) => s.replace(/(^|_)([a-zA-Z0-9])/g, (_, __, c) => c.toUpperCase());
const prop = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name));
const jsdoc = (text, ind) => {
  const t = (text ?? "").trim().replace(/\*\//g, "*\\/");
  return t ? `${ind}/** ${t} */\n` : "";
};
const uniq = (xs) => [...new Set(xs)];

/** `#/$defs/node` is any node (a built-in op or a component instance). */
function refName(ref) {
  const m = /^#\/\$defs\/(.+)$/.exec(ref);
  if (!m || !(m[1] in defs)) throw new Error(`unknown $ref ${ref}`);
  return m[1] === "node" ? "AnyNode" : pascal(m[1]);
}

// Object branches of a def's anyOf/oneOf told apart by one required key get
// their own names: animated's {"keys": ...} is AnimatedKeys.
const named = new Map();
for (const [name, def] of Object.entries(defs)) {
  for (const b of def.anyOf ?? def.oneOf ?? []) {
    if (b.properties && b.required?.length === 1) named.set(b, pascal(name) + pascal(b.required[0]));
  }
}

/** The alternatives of a schema fragment, as TypeScript types. */
function alts(s, ind, self) {
  if (s === true || s == null) return ["unknown"];
  if (s !== self && named.has(s)) return [named.get(s)];
  if (s.$ref) return [refName(s.$ref)];
  if (s.anyOf || s.oneOf) return (s.anyOf ?? s.oneOf).flatMap((a) => alts(a, ind));
  if (s.enum) return s.enum.map((v) => JSON.stringify(v));
  if ("const" in s) return [JSON.stringify(s.const)];
  const type = s.type ?? (s.properties || s.required ? "object" : undefined);
  switch (type) {
    case "number":
    case "integer":
      return ["number"];
    case "boolean":
      return ["boolean"];
    case "string":
      if (s.pattern?.startsWith("^#")) return ["HexColor"];
      if (s.pattern?.startsWith("^\\$")) return ["`$${string}`"];
      return ["string"];
    case "array": {
      if (s.prefixItems) {
        const parts = s.prefixItems.map((p) => ts(p, ind));
        const out = [];
        for (let n = s.minItems ?? parts.length; n <= parts.length; n++) out.push(`[${parts.slice(0, n).join(", ")}]`);
        return out;
      }
      const item = ts(s.items, ind);
      const min = s.minItems ?? 0;
      const max = s.maxItems;
      if (min >= 1 && max !== undefined && max <= 4) {
        const out = [];
        for (let n = min; n <= max; n++) out.push(`[${Array(n).fill(item).join(", ")}]`);
        return out;
      }
      return [item.includes(" | ") ? `(${item})[]` : `${item}[]`];
    }
    case "object":
      return [object(s, ind)];
    default:
      return ["unknown"];
  }
}

function ts(s, ind = "", self) {
  return uniq(alts(s, ind, self)).join(" | ");
}

/** A template literal type for a pattern's literal prefix, e.g. `axis_${string}`. */
function patternKey(pattern) {
  const m = /^\^([A-Za-z0-9_\-]+)/.exec(pattern);
  return m ? `\`${m[1]}\${string}\`` : null;
}

function members(s, ind, override = {}) {
  const req = new Set(s.required ?? []);
  const lines = [];
  for (const [k, v] of Object.entries(s.properties ?? {})) {
    const t = override[k] ?? ts(v, ind + "  ");
    lines.push(jsdoc(v.description, ind + "  ") + `${ind}  ${prop(k)}${req.has(k) ? "" : "?"}: ${t};`);
  }
  for (const k of req) if (!(k in (s.properties ?? {}))) lines.push(`${ind}  ${prop(k)}: unknown;`);
  for (const [p, v] of Object.entries(s.patternProperties ?? {})) {
    const key = patternKey(p);
    if (key) lines.push(jsdoc(`Keys matching \`${p}\`: ${v.description ?? ""}`, ind + "  ") + `${ind}  [key: ${key}]: ${ts(v, ind + "  ")};`);
  }
  return lines;
}

function object(s, ind) {
  const ap = s.additionalProperties;
  if (!s.properties && !s.patternProperties && !s.required) {
    return `Record<string, ${ap && typeof ap === "object" ? ts(ap, ind) : "unknown"}>`;
  }
  return `{\n${members(s, ind).join("\n")}\n${ind}}`;
}

// --- $defs --------------------------------------------------------------

let out = `// Generated by scripts/gen-types.mjs from ${schema.$id ?? "the document schema"}.
// Do not edit: refresh schema/v1.json and run \`npm run gen\`.

/** A \`#rgb\`, \`#rgba\`, \`#rrggbb\` or \`#rrggbbaa\` color. */
export type HexColor = \`#\${string}\`;

`;

const hasAnimated = "animated" in defs;
const hasComponentParam = "component_param" in defs;

for (const [name, def] of Object.entries(defs)) {
  if (name === "node") continue;
  const tname = pascal(name);
  for (const b of def.anyOf ?? def.oneOf ?? []) {
    if (!named.has(b)) continue;
    out += jsdoc(b.description ?? `One form of \`${tname}\`.`, "") + `export interface ${named.get(b)} {\n${members(b, "").join("\n")}\n}\n\n`;
  }
  out += jsdoc(def.description, "");
  if ((def.type === "object" || def.properties) && !def.anyOf && !def.oneOf) {
    out += `export interface ${tname} {\n${members(def, "", name === "component" ? { nodes: "Record<string, AnyNode>" } : {}).join("\n")}\n}\n\n`;
  } else {
    const parts = uniq(alts(def, "", def));
    out += parts.length > 3 ? `export type ${tname} =\n${parts.map((p) => `  | ${p}`).join("\n")};\n\n` : `export type ${tname} = ${parts.join(" | ")};\n\n`;
  }
}

const extra = [hasAnimated && "Animated", hasComponentParam && "ComponentParam"].filter(Boolean);
out += `/** A param: a plain value${hasAnimated ? ", animated" : ""}${hasComponentParam ? ", or (inside a component) one of the component's params" : ""}. */
export type Param<T> = T${extra.map((e) => ` | ${e}`).join("")};

`;

// --- ops ----------------------------------------------------------------

const ANIMATED = "#/$defs/animated";
const CPARAM = "#/$defs/component_param";

/** A param's type: Param<T> when it may be animated and a component param. */
function paramType(s) {
  const branches = s.anyOf ?? [s];
  const plain = branches.filter((b) => b.$ref !== ANIMATED && b.$ref !== CPARAM);
  const wrapped = branches.some((b) => b.$ref === ANIMATED) && (!hasComponentParam || branches.some((b) => b.$ref === CPARAM));
  const inner = uniq(plain.flatMap((b) => alts(b, "  "))).join(" | ");
  return wrapped && plain.length < branches.length ? `Param<${inner}>` : ts(s, "  ");
}

const ops = defs.node.allOf.map((r) => {
  const op = r.if.properties.op.const;
  const then = r.then.properties;
  return { op, name: pascal(op), params: then.params ?? {}, ports: Object.keys(then.inputs?.properties ?? {}), layers: Boolean(then.inputs?.items) };
});

out += `/** Every op name. */
export type OpName =
${ops.map((o) => `  | ${JSON.stringify(o.op)}`).join("\n")};

/** Every op name, at runtime. */
export const OPS: readonly OpName[] = [
${ops.map((o) => `  ${JSON.stringify(o.op)},`).join("\n")}
];

`;

for (const o of ops) {
  out += `/** Params of \`${o.op}\`. */\nexport interface ${o.name}Params {\n`;
  for (const [name, s] of Object.entries(o.params.properties ?? {})) {
    out += jsdoc(s.description, "  ") + `  ${prop(name)}?: ${paramType(s)};\n`;
  }
  for (const [p, s] of Object.entries(o.params.patternProperties ?? {})) {
    const key = patternKey(p);
    if (key) out += jsdoc(`Keys matching \`${p}\`: ${s.description ?? ""}`, "  ") + `  [key: ${key}]: ${paramType(s)};\n`;
  }
  out += `}\n\n`;
  out += `/** A \`${o.op}\` node. */\nexport interface ${o.name}Node {\n  op: ${JSON.stringify(o.op)};\n  params?: ${o.name}Params;\n`;
  if (o.ports.includes("*")) out += `  /** Any port names, each the id of the node feeding it. */\n  inputs?: Record<string, string>;\n`;
  else if (o.layers) out += `  /** Port name to the id of the node feeding it, or the ids of the layers, bottom first. */\n  inputs?: { ${o.ports.map((p) => `${prop(p)}?: string`).join("; ")} } | string[];\n`;
  else if (o.ports.length) out += `  /** Port name to the id of the node feeding it. */\n  inputs?: { ${o.ports.map((p) => `${prop(p)}?: string`).join("; ")} };\n`;
  out += `  timing?: Timing;\n}\n\n`;
}

const nodeProps = defs.node.properties;
out += `/** A node of a built-in op, discriminated by \`op\`. */
export type Node =
${ops.map((o) => `  | ${o.name}Node`).join("\n")};

/** Params of each op. */
export interface OpParams {
${ops.map((o) => `  ${prop(o.op)}: ${o.name}Params;`).join("\n")}
}

/** The params of op \`O\`. */
export type ParamsOf<O extends OpName> = OpParams[O];

/** The node type of op \`O\`. */
export type NodeOf<O extends OpName> = Extract<Node, { op: O }>;

/** A node whose op names a component in \`document.components\`. */
export interface ComponentNode {
  /** The component's name. */
  op: string;
  params?: Record<string, ${"value" in defs ? "Value" : "unknown"}>;
  inputs?: ${ts(nodeProps.inputs)};
  timing?: Timing;
}

/** Any node: a built-in op, or a component instance. */
export type AnyNode = Node | ComponentNode;

/** Whether \`node\` is a node of op \`op\` (narrows its params). */
export function isOp<O extends OpName>(node: AnyNode, op: O): node is NodeOf<O> {
  return node.op === op;
}

/** A font pin: this file answers for its family, weight and style. */
export interface FontPin {
  family: string;
  weight?: number;
  style?: string;
  /** A reference (asset://, https://, gs://, s3://, r2://), or a local path the client uploads. */
  src: string;
  sha256?: string;
}

/** Free-form notes and tool data, echoed in render receipts. Conventions from the API. */
export interface Meta {
  /** Whatever wrote the document. */
  composer?: { name?: string; version?: string; revision?: string };
  /** Font files that answer for their family, weight and style in this render. */
  fonts?: FontPin[];
  /** Archive reference to the members checked after unpacking. */
  archives?: Record<string, { members: Record<string, { sha256?: string; size?: number }> }>;
  [key: string]: unknown;
}

${jsdoc(`${schema.title}. ${schema.description ?? ""}`, "")}export interface Document {
${members(schema, "", { meta: "Meta", nodes: "Record<string, AnyNode>" }).join("\n")}
}
`;

writeFileSync(outPath, out);
const params = ops.reduce((n, o) => n + Object.keys(o.params.properties ?? {}).length, 0);
console.log(`wrote ${outPath}: ${ops.length} ops, ${params} params`);
